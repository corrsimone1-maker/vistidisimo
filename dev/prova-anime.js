// Seconda prova: numerazione assoluta (Naruto Shippuden), colori di stato, avvio con dati già in cache.
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const path = require('path');
const { makeMocks } = require('./mock.js');
const OUT = process.argv[2] || require('os').tmpdir();
// Le due repo devono stare una accanto all'altra (…/vistidisimo e …/vistidisimo-dati).
const ROOT = path.resolve(__dirname, '..', '..');
const LIB = process.env.VDS_LIB || path.join(ROOT, 'vistidisimo-dati', 'library.json');
(async () => {
  const srv = spawn('python3', ['-m', 'http.server', '8124', '--bind', '127.0.0.1', '--directory', ROOT], { stdio: 'ignore' });
  await new Promise((r) => setTimeout(r, 800));
  const lib0 = require(LIB);
  const animeKeys = new Set(lib0.lists.find((l) => l.title === 'Anime').items.map((e) => e.key));
  const M = makeMocks(LIB, { animeKeys });
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  await ctx.route('https://api.github.com/**', M.github);
  await ctx.route('https://api.themoviedb.org/**', M.tmdb);
  await ctx.route('https://image.tmdb.org/**', M.image);
  await ctx.addInitScript(() => { if (!localStorage.getItem('vds.ghToken')) { localStorage.setItem('vds.ghToken', 'x'); localStorage.setItem('vds.tmdbToken', 'y'); } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  const shot = async (name, full = false) => { await page.waitForTimeout(350); await page.screenshot({ path: path.join(OUT, name + '.png'), fullPage: full }); };
  const base = 'http://127.0.0.1:8124/vistidisimo/';
  await page.goto(base + '#/home');
  await page.waitForSelector('.wordmark');
  await page.waitForFunction(() => !document.querySelector('.banner'), null, { timeout: 60000 });
  await page.waitForTimeout(1200);
  // Naruto Shippuden: prossimo episodio con numerazione assoluta
  await page.goto(base + '#/prossimi');
  await page.waitForTimeout(1200);
  const rows = await page.$$eval('.ep-card', (els) => els.map((e) => e.querySelector('.ep-show').textContent + ' | ' + e.querySelector('.ep-code').textContent));
  console.log(rows.filter((r) => /Naruto|Hunter/.test(r)).join('\n'));
  const it = lib0.items['tv:31910'];
  const last = Object.entries(it.eps).filter(([s]) => s !== '0').map(([s, v]) => [Number(s), Math.max(...Object.keys(v).map(Number))]).sort((a, b) => a[0] - b[0]).pop();
  console.log('Naruto Shippuden ultimo visto nei dati:', last);
  await page.goto(base + '#/t/tv/31910');
  await page.waitForSelector('.season');
  await page.waitForTimeout(800);
  const heads = await page.$$('.season-head');
  await heads[1].click();
  await page.waitForTimeout(800);
  const firstEps = await page.$$eval('.season.open .ep .ep-n', (els) => els.slice(0, 3).map((e) => e.textContent));
  console.log('Stagione 2, primi numeri:', firstEps.join(','));
  await shot('30-naruto');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.click('[data-act=d-status]');
  await shot('31-stato-colori');
  await page.click('.sheet-bg');
  await page.goto(base + '#/t/movie/129');
  await page.waitForSelector('.d-head');
  await page.waitForTimeout(600);
  await page.evaluate(() => window.scrollTo(0, 500));
  await shot('32-film-rivisto');
  // ricarica completa: deve partire dalla cache senza riscaricare tutto da TMDB
  let tmdbCalls = 0;
  await ctx.route('https://api.themoviedb.org/**', async (route) => { tmdbCalls++; return M.tmdb(route); });
  await page.goto(base + '#/home');
  await page.reload();
  await page.waitForSelector('.scroller img');
  await page.waitForTimeout(2500);
  console.log('richieste TMDB dopo ricarica:', tmdbCalls);
  await shot('33-home-ricaricata');
  console.log('ERRORI:', errors.length ? errors.join('\n') : 'nessuno');
  console.log('dimensioni: library.json', M.files['library.json'].length, 'meta.json', (M.files['meta.json'] || '').length);
  await browser.close(); srv.kill();
})().catch((e) => { console.error(e); process.exit(1); });
